function plated(id: string, nameKey: string, descKey: string, rarity: Rarity, into: Rarity): StickerDef {
  return {
    id,
    nameKey,
    descKey,
    family: 'trigger',
    rarity,
    icon: 'bow',
    ability: {
      id: `${id}.plate`,
      trigger: 'onApply',
      target: 'self',
      once: true,
      effects: [
        { op: 'transform', randomRarity: into },
        { op: 'exhaustSticker', stickerId: id },
      ],
    },
    archetypes: ['buff'],
  };
}

