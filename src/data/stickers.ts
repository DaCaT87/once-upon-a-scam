const RARITY_RANK: Record<Rarity, number> = {
  bronze: 0,
  silver: 1,
  gold: 2,
  platinum: 3,
  diamond: 4,
};
STICKERS.sort((a, b) => {
  const byRarity = RARITY_RANK[a.rarity] - RARITY_RANK[b.rarity];
  if (byRarity !== 0) return byRarity;
  return translate('en', a.nameKey).localeCompare(translate('en', b.nameKey), 'en', { sensitivity: 'base' });
});

export const STICKER_BY_ID = new Map(STICKERS.map((s) => [s.id, s]));
STICKER_BY_ID.set('bandage-roll', STICKER_BY_ID.get('life-potion')!);
STICKER_BY_ID.set('boom-stick', STICKER_BY_ID.get('revenge-bomb')!);

export function grantableStickers(): StickerDef[] {
  return STICKERS.filter((s) => s.frame !== 'monster' && s.id !== 'trash' && s.id !== 'poison');
}

export function shopStickers(): StickerDef[] {
  return grantableStickers().filter((s) => s.rarity !== 'diamond');
}

export function huntStickers(): StickerDef[] {
  return STICKERS.filter((s) => s.frame === 'monster');
}

/** Boss stickers shown in the library. The other hunt prizes stay out of the book. */
const LIBRARY_HUNT_IDS = new Set(['endless-hunger', 'mythic-treasure', 'woodsmans-axe', 'filth', 'cocoon']);

export function libraryHuntStickers(): StickerDef[] {
  return STICKERS.filter((s) => LIBRARY_HUNT_IDS.has(s.id));
}
